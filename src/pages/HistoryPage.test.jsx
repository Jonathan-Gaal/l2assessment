import { describe, it, expect, beforeEach } from 'vitest'
import { render, screen } from '@testing-library/react'
import HistoryPage from './HistoryPage'

function seedHistory(entries) {
  localStorage.setItem('triageHistory', JSON.stringify(entries))
}

describe('HistoryPage fallback badge', () => {
  beforeEach(() => {
    localStorage.clear()
  })

  it('shows a Fallback badge for entries generated by the mock fallback', () => {
    seedHistory([
      {
        message: 'Server down now',
        category: 'Technical Problem',
        urgency: 'High',
        recommendedAction: 'Suggest user to restart their browser.',
        reasoning: 'Keyword-based guess.',
        source: 'mock',
        timestamp: new Date().toISOString(),
      },
    ])

    render(<HistoryPage />)

    expect(screen.getByText('⚠ Fallback')).toBeInTheDocument()
  })

  it('does not show a Fallback badge for real AI-sourced entries', () => {
    seedHistory([
      {
        message: 'Why was I charged twice?',
        category: 'Billing Issue',
        urgency: 'Medium',
        recommendedAction: 'Ask user to check billing portal.',
        reasoning: 'Real AI reasoning.',
        source: 'ai',
        timestamp: new Date().toISOString(),
      },
    ])

    render(<HistoryPage />)

    expect(screen.queryByText('⚠ Fallback')).not.toBeInTheDocument()
  })

  it('does not crash on legacy entries with no source field', () => {
    seedHistory([
      {
        message: 'Old entry before this field existed',
        category: 'General Inquiry',
        urgency: 'Low',
        recommendedAction: 'Respond with FAQ link.',
        reasoning: 'Legacy reasoning.',
        timestamp: new Date().toISOString(),
      },
    ])

    render(<HistoryPage />)

    expect(screen.getByText(/Old entry before this field existed/)).toBeInTheDocument()
    expect(screen.queryByText('⚠ Fallback')).not.toBeInTheDocument()
  })
})
